i18n.configure({
  locales: ['en', 'de', 'es', 'fa', 'ko', 'pt', 'ru', 'tr'], // Supported locales
  defaultLocale: 'en', // Default locale if none is specified
  autoReload: true, // Reload translations automatically when changed (development)
  syncFiles: true, // Create new locale files on init (only for initial setup, usually false in prod)
  directory: path.join(__dirname, '../locales'), // Directory to store translation json files
  extension: '.json', // File extension for translation files
  objectNotation: true, // Enables nested object structure for translations
  register: global // Registers the __ and __n functions globally
});

/**
 * Custom middleware to load messages into the i18n instance.
 * In a real application, these messages would typically be loaded from files
 * in the `locales` directory using `i18n.configure` directly.
 * For this conversion, we directly embed the messages.
 */
i18n.init = (req, res, next) => {
  // Set up res.__ and res.__n functions to be available in templates
  res.locals.__ = res.__ = (...args) => i18n.__(...args);
  res.locals.__n = res.__n = (...args) => i18n.__n(...args);

  // Determine locale from query parameter 'lang' or session
  let locale = req.query.lang || req.session.locale || i18n.getLocale(req);

  // Validate if the requested locale is supported
  if (!i18n.getLocales().includes(locale)) {
    locale = i18n.getDefaultLocale(); // Fallback to default if not supported
  }

  i18n.setLocale(req, locale);
  req.session.locale = locale; // Save locale in session for persistence

  // Manually register message data (as we are not loading from files directly)
  // This part is a workaround since i18n-node expects files, but we have in-memory objects
  i18n.getCatalog(locale, (err, catalog) => {
    if (err) {
      console.error(`Error getting i18n catalog for ${locale}:`, err);
    } else {
      // Merge current locale messages with fallback (defaultLocale messages.properties)
      // The i18n library handles fallbacks itself by loading from directory.
      // Since we hardcoded `messages.properties` as the default source in `messages` object,
      // we ensure it's available.
      if (locale !== i18n.getDefaultLocale()) {
        Object.assign(catalog, messages['messages.properties']);
      }
      const localeMessagesKey = `messages_${locale}.properties`;
      if (messages[localeMessagesKey]) {
        Object.assign(catalog, messages[localeMessagesKey]);
      } else if (messages['messages.properties'] && locale === i18n.getDefaultLocale()) {
        Object.assign(catalog, messages['messages.properties']);
      }
    }
  });


  next();
};

